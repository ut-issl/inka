//! Extracting a test's contract body from its source file.
//!
//! The body is the test's own definition — attributes included — sliced
//! verbatim from the file, so reviewers approve exactly what is written.
//! Module paths resolve the way rustc resolves them: inline `mod` blocks,
//! `name.rs` / `name/mod.rs` files and `#[path]` overrides. Two test
//! shapes are supported: a plain `fn` item (whatever test attribute marks
//! it) and a `fn` inside a `proptest!` block, where the slice keeps the
//! parameter strategies. A `#![proptest_config(..)]` line configures the
//! whole block and is not part of any one test's body.
//!
//! Anything the resolver cannot find is an explicit error, never a guess:
//! a test generated by a macro this adapter does not understand must fail
//! loudly rather than ship some other code as its body.

use std::path::{Path, PathBuf};

use proc_macro2::{Delimiter, TokenTree};
use syn::spanned::Spanned;

use crate::error::Error;

/// Extracts the contract body of one test, named by its path inside the
/// binary (for example `tests::passes`), starting from the target's root
/// source file.
pub fn body(root_file: &Path, test_id: &str, test_path: &str) -> Result<String, Error> {
    let mut segments: Vec<&str> = test_path.split("::").collect();
    let function = segments.pop().unwrap_or(test_path);

    let mut file = root_file.to_path_buf();
    let mut text = read(&file)?;
    let mut items = parse(&file, &text)?;
    // The directory that out-of-line submodules of the current module
    // resolve against. A crate root file behaves like a mod.rs: its
    // submodules live next to it.
    let mut dir = parent(&file);

    for segment in segments {
        let module = take_module(&mut items, segment).ok_or_else(|| Error::BodyNotFound {
            test_id: test_id.to_owned(),
            detail: format!("no `mod {segment}` in {}", file.display()),
        })?;
        if let Some((_, content)) = module.content {
            items = content;
            dir.push(segment);
            continue;
        }
        file = module_file(&dir, segment, &module.attrs).ok_or_else(|| Error::BodyNotFound {
            test_id: test_id.to_owned(),
            detail: format!(
                "`mod {segment};` resolves to neither {segment}.rs nor {segment}/mod.rs under {}",
                dir.display()
            ),
        })?;
        text = read(&file)?;
        items = parse(&file, &text)?;
        dir = module_dir(&file);
    }

    find_body(&items, function, &text).ok_or_else(|| Error::BodyNotFound {
        test_id: test_id.to_owned(),
        detail: format!(
            "no `fn {function}` (plain or inside a `proptest!` block) in {}",
            file.display()
        ),
    })
}

/// Removes and returns the module named `segment` from `items`.
fn take_module(items: &mut Vec<syn::Item>, segment: &str) -> Option<syn::ItemMod> {
    let position = items
        .iter()
        .position(|item| matches!(item, syn::Item::Mod(module) if module.ident == segment))?;
    match items.swap_remove(position) {
        syn::Item::Mod(module) => Some(module),
        _ => None,
    }
}

/// Resolves an out-of-line `mod segment;` to its file: a `#[path]`
/// override when present, else `segment.rs`, else `segment/mod.rs`.
fn module_file(dir: &Path, segment: &str, attrs: &[syn::Attribute]) -> Option<PathBuf> {
    if let Some(path) = path_attribute(attrs) {
        // The reference resolves `#[path]` against the enclosing module's
        // directory — inline module components included — which is `dir`.
        return Some(dir.join(path));
    }
    let file = dir.join(format!("{segment}.rs"));
    if file.exists() {
        return Some(file);
    }
    let file = dir.join(segment).join("mod.rs");
    file.exists().then_some(file)
}

/// The string value of a `#[path = "..."]` attribute, if any.
fn path_attribute(attrs: &[syn::Attribute]) -> Option<String> {
    attrs.iter().find_map(|attr| {
        if !attr.path().is_ident("path") {
            return None;
        }
        let syn::Meta::NameValue(pair) = &attr.meta else {
            return None;
        };
        let syn::Expr::Lit(literal) = &pair.value else {
            return None;
        };
        match &literal.lit {
            syn::Lit::Str(value) => Some(value.value()),
            _ => None,
        }
    })
}

/// The directory submodules of a just-loaded module file resolve against.
fn module_dir(file: &Path) -> PathBuf {
    let base = parent(file);
    if file.file_name().is_some_and(|name| name == "mod.rs") {
        base
    } else {
        base.join(file.file_stem().unwrap_or_default())
    }
}

fn parent(file: &Path) -> PathBuf {
    file.parent().unwrap_or_else(|| Path::new("")).to_path_buf()
}

fn read(file: &Path) -> Result<String, Error> {
    std::fs::read_to_string(file).map_err(|source| Error::Read {
        path: file.to_owned(),
        source,
    })
}

fn parse(file: &Path, text: &str) -> Result<Vec<syn::Item>, Error> {
    syn::parse_file(text)
        .map(|parsed| parsed.items)
        .map_err(|source| Error::Parse {
            path: file.to_owned(),
            source,
        })
}

/// Finds the test function among a module's items and slices its source.
fn find_body(items: &[syn::Item], function: &str, text: &str) -> Option<String> {
    for item in items {
        match item {
            syn::Item::Fn(fn_item) if fn_item.sig.ident == function => {
                return Some(text[fn_item.span().byte_range()].to_owned());
            }
            syn::Item::Macro(macro_item) if is_proptest(&macro_item.mac) => {
                if let Some(body) = proptest_slice(&macro_item.mac.tokens, function, text) {
                    return Some(body);
                }
            }
            _ => {}
        }
    }
    None
}

/// Whether a macro invocation is a `proptest!` block.
fn is_proptest(mac: &syn::Macro) -> bool {
    mac.path
        .segments
        .last()
        .is_some_and(|segment| segment.ident == "proptest")
}

/// Slices one `fn` out of a `proptest!` block's token stream, outer
/// attributes and parameter strategies included. The block's contents are
/// not plain Rust (`a in 0..10` parameters), so this walks tokens instead
/// of parsing items, using their spans to cut the original text.
fn proptest_slice(tokens: &proc_macro2::TokenStream, function: &str, text: &str) -> Option<String> {
    let trees: Vec<TokenTree> = tokens.clone().into_iter().collect();
    let mut attr_start: Option<usize> = None;
    let mut index = 0;
    while index < trees.len() {
        match &trees[index] {
            TokenTree::Punct(punct) if punct.as_char() == '#' => {
                // `#![...]` configures the whole block, not the next item.
                let inner = matches!(
                    trees.get(index + 1),
                    Some(TokenTree::Punct(bang)) if bang.as_char() == '!'
                );
                if inner {
                    index += 3;
                    attr_start = None;
                    continue;
                }
                if attr_start.is_none() {
                    attr_start = Some(punct.span().byte_range().start);
                }
                index += 2;
            }
            TokenTree::Ident(ident) if ident == "fn" => {
                let name_matches = matches!(
                    trees.get(index + 1),
                    Some(TokenTree::Ident(name)) if name == function
                );
                let start = attr_start.unwrap_or_else(|| ident.span().byte_range().start);
                // The body is the next brace group after the signature.
                let mut next = index + 2;
                let (body_index, end) = loop {
                    match trees.get(next) {
                        Some(TokenTree::Group(group)) if group.delimiter() == Delimiter::Brace => {
                            break (next, group.span().byte_range().end);
                        }
                        Some(_) => next += 1,
                        None => return None,
                    }
                };
                if name_matches {
                    return Some(text[start..end].to_owned());
                }
                index = body_index + 1;
                attr_start = None;
            }
            _ => index += 1,
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;

    use super::body;

    fn fixture(name: &str) -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("tests/fixtures/sample")
            .join(name)
    }

    #[test]
    fn slices_a_plain_test_with_its_attributes() {
        let extracted = body(
            &fixture("src/lib.rs"),
            "sample::tests::ignored",
            "tests::ignored",
        )
        .expect("the fixture test exists");

        assert_eq!(
            extracted,
            "#[test]\n    #[ignore = \"declared but skipped\"]\n    fn ignored() {\n        \
             unreachable!(\"never run by the default profile\");\n    }"
        );
    }

    #[test]
    fn walks_nested_inline_modules() {
        let extracted = body(
            &fixture("src/lib.rs"),
            "sample::tests::nested::deep_passes",
            "tests::nested::deep_passes",
        )
        .expect("the nested fixture test exists");

        assert!(extracted.starts_with("#[test]"));
        assert!(extracted.contains("fn deep_passes()"));
    }

    #[test]
    fn walks_into_a_file_module() {
        let extracted = body(
            &fixture("src/lib.rs"),
            "sample::util::tests::doubles",
            "util::tests::doubles",
        )
        .expect("the file-module fixture test exists");

        assert!(extracted.contains("fn doubles()"));
    }

    #[test]
    fn slices_a_proptest_function_with_its_strategies() {
        let extracted = body(
            &fixture("tests/props.rs"),
            "sample::props::add_commutes",
            "add_commutes",
        )
        .expect("the proptest fixture test exists");

        assert_eq!(
            extracted,
            "#[test]\n    fn add_commutes(a in 0u64..1000, b in 0u64..1000) {\n        \
             prop_assert_eq!(sample::add(a, b), sample::add(b, a));\n    }"
        );
    }

    #[test]
    fn reports_an_unknown_function_with_its_file() {
        let error = body(&fixture("src/lib.rs"), "sample::tests::gone", "tests::gone")
            .expect_err("no such test");

        let message = error.to_string();
        assert!(message.contains("sample::tests::gone"));
        assert!(message.contains("lib.rs"));
    }

    #[test]
    fn reports_an_unknown_module() {
        let error =
            body(&fixture("src/lib.rs"), "sample::ghost::t", "ghost::t").expect_err("no module");

        assert!(error.to_string().contains("no `mod ghost`"));
    }
}
